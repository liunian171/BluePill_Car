#include "uart.h"
#include <stdint.h>


/*==============================================================================
 *  发送
 *==============================================================================*/

/**
 * @brief  阻塞发送 len 字节
 * @param  hUART  UART 句柄
 * @param  data   待发送数据缓冲区
 * @param  len    发送字节数
 * @return 0 成功, -1 失败
 */
int8_t uart_send(UART_Handle *hUART, const uint8_t *data, uint16_t len)
{
    return hUART->ops->send(hUART->huart, data, len);
}


