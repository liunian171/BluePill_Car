#ifndef CAR_CONFIG_H
#define CAR_CONFIG_H

/**
 * ============================================================================
 *  car_config.h — 整车配置单（组装层知识）
 * ============================================================================
 *
 *  层位：组装层配置（"这台车启用哪些功能 / 标定多少"是车的知识）。
 *  设计决议：doc/开发跟踪.md §设计决议 2026-09-19（功能编译开关，空壳替换方案）。
 *
 *  ▸ 谁可以 include 本文件 ◂
 *    ✅ 组装层 main.c
 *    ✅ CMakeLists.txt（按本文件的宏取舍源文件，单一真值源在这里）
 *    ❌ 组件层 / 桥接层 / 器件层 / 驱动层 —— 禁止 include！
 *       （组件依赖白名单仅 <stdint.h>，义务 7；功能宏进组件 = PC 桩不可编译）
 *       功能开关只允许作用于两处：CMake 源文件列表、组装层接线。
 *
 *  ▸ 开关生效方式（空壳替换为主，组装层接线条件编译为辅）◂
 *    ① 空壳替换（优先，main.c 零修改）：
 *       宏 = 1 → CMake 编 line_follower.c（完整功能）
 *       宏 = 0 → CMake 编 line_follower_stub.c（空实现，12+ 处
 *               line_follower_enable(0) 接管权调用自然变 no-op）
 *    ② 组装层接线条件编译（无对应源文件可替换时用，如链路开关）：
 *       main.c 里 `LINK_*_ENABLED` = 本文件宏 → 禁用链路"接线不存在"
 *       （详见 main.c 的 [P3 双开关] 注释段）
 *
 *  ▸ 改动流程 ◂
 *    ① 改下面的宏值 → ② 必须重新 `cmake --preset Release`（GLOB/取舍在 configure
 *    期完成，只 build 不会生效；**必须 Release**：Debug(-O0) 链接溢出 64KB，
 *    见 AGENTS §三）→ ③ 编译看 Flash/RAM → ④ 回写开发跟踪。
 *
 *  ▸ 本文件承载两类内容（2026-09-19 标定集中后）◂
 *    ① **功能/链路编译开关**（见下 §功能开关 / §链路开关）
 *    ② **整车标定表**（见下 §整车标定）—— 数值只在这里出现一次（单一真值源），
 *       由组装层在"配置结构体初始化"处引用；下层一律经 cfg 结构注入（义务 1），
 *       **不得**为了取值而 include 本文件。
 * ============================================================================
 */

/* ---------------------------------------------------------------------------
 *  功能开关（1 = 编译进固件 / 0 = 编译期剔除）
 * ------------------------------------------------------------------------- */

/* 巡线功能（line_follower 状态机 + 5 路灰度决策链）
 * 0 的含义：巡线永不接管运动意图；L/LA/GK/GD/GS/GI/GC/GT 命令变为
 *          no-op 空壳（部分应答仍回显参数，真伪以 OLED 页 7 "LINE:OFF" 为准）
 * 改回 1 的条件：巡线实车整定重启（L-4）或独立小车模式启用时；
 *          当前口径（2026-09-19）：ROS 下位机模式主用，巡线暂不使用 → 0   */
#define CAR_FEATURE_LINE_FOLLOWER 0

/* ---------------------------------------------------------------------------
 *  链路开关（双链路仲裁 P3 开关收口，详 doc/双链路仲裁设计文档.md §5）
 *  语义 = "这条链路的接线不存在"，**不改协议、不改组件**，只改组装层接线。
 * ------------------------------------------------------------------------- */

/* USB CDC 链路（主用：ROS 下位机主链，枚举为 0483:5740 的 COM 口）
 * 0 的含义：usb ringbuf 不消费 / usb_alive 恒假 / 仲裁固定走 UART /
 *          LINK USB 命令被拒（回 LINK:OFF）
 * ⚠️ =0 **不省 Flash** —— USB 中间件由 CubeMX 生成，编译剔除需动生成代码，
 *    12KB 成本已付，不值（设计文档 §5 明确）；本开关是"语义收口"不是"瘦身手段" */
#define CAR_FEATURE_USB        1

/* BT04 蓝牙 SPP 链路（备链：USART2 PA2/PA3，9600-8N1）
 * 0 的含义：不开 UART 中断接收 / UART 发送 no-op / 仲裁固定走 USB /
 *          LINK UART 命令被拒（回 LINK:OFF）
 * 典型用法：纯 USB 场测（不接 BT04，免得 PA3 悬空输入引入噪声） */
#define CAR_FEATURE_UART       1

/* ⚠️ 两宏不得同时为 0（车失联）—— CMakeLists 在 configure 期直接报错拒绝。
 * 四组合（00 被拒 / 01 / 10 / 11）均在编译矩阵中验证，见 doc/开发跟踪.md P3 条。 */

/* ===========================================================================
 *  整车标定表（2026-09-19 集中；原散落在 main.c 的各配置结构体里）
 * ===========================================================================
 *
 *  ▸ 使用方式 ◂
 *    组装层在配置结构体初始化处引用这些宏（如 g_motor_cfg / g_spd_cfg /
 *    g_odom_cfg），下层组件/桥接层经 cfg 结构拿到数值 —— 它们看不见本文件。
 *
 *  ▸ 改值的后果与前置 ◂
 *    · 标定值改了要**重新标定相邻值**（见每组注释里的"镜像/同源"说明）
 *    · 只改数值**不需要重新 configure**（与开关宏不同），但必须重新编译烧录
 *    · 改动后按 AGENTS §5.4 闭环：开发跟踪记值 + 真机回归（tools/link_regress.py）
 * =========================================================================== */

/* ---- 编码器 / 轮组（机械标定，实测值 → README §1 权威）---- */
#define CAR_PPR                 1466        /* 编码器每转脉冲数（实测；E1/E2 相同）*/
#define CAR_ENC_SPAN            65536       /* 16 位定时器计数模值（回绕校正）；换 32 位编码器置 0 */
#define CAR_WHEEL_CIRC_MM       205.0f      /* 车轮周长 mm（README 权威 20.5cm；odom 里程换算）*/
#define CAR_WHEEL_RADIUS_MM     32.5f       /* 车轮半径 mm（电机桥 m/s ↔ rpm 换算）*/
#define CAR_WHEEL_TRACK_MM      0.0f        /* 轮距 mm —— ⚠️ 未标定：本车 Δθ 走 IMU yaw 差分，轮距不参与 */

/* ---- 电机（TB6612 + MG513 减速电机）---- */
#define CAR_MOTOR_MAX_RPM       319.0f      /* 实测标定上限（勿用数据手册 200；速度环输出限幅同源）*/
#define CAR_MOTOR_PWM_HZ        20000       /* TIM1 PWM 频率（超出可听域）*/
/* ⚠️ 镜像对：驱动侧取反与反馈侧符号是**同一个硬件事实的两面**（M1 驱动与编码器均反相）。
 *    改一个必须同时改另一个，否则正反馈飞车（2026-09-13 真机实证：M1 上电持续加速） */
#define CAR_M1_DRIVE_SIGN       (-1)        /* M1 驱动侧方向取反 */
#define CAR_M1_FB_SIGN          (-1)        /* M1 速度环/里程计反馈符号（镜像对，见上）*/

/* ---- 速度环（SIMC 阶跃辨识值，2026-09-13；详见 tools/step_ident.py）---- */
#define CAR_SPD_KP              0.87f       /* ×100 下发即 PID 命令里的 87 */
#define CAR_SPD_KI              0.40f
#define CAR_SPD_KD              0.0f
#define CAR_SPD_FF_GAIN         1.0f        /* 前馈系数（辨识 1/K ≈ 1.0）*/

/* ---- IMU 安装（MPU6050）---- */
#define CAR_YAW_SIGN            (-1)        /* yaw 顺时针为正（安装实测）→ 取反成"逆时针为正"
                                             * （2026-09-14 真机：顺时针转车头 yaw +16.5°）*/

/* ---- 舵机（输出域角度，实测标定；物理角 = 输出域 + PHYS_OFFSET）---- */
#define CAR_SERVO_LIM_MIN       (-115.0f)   /* 右满舵（输出域下限）*/
#define CAR_SERVO_LIM_MAX       (-65.0f)    /* 左满舵（输出域上限）*/
#define CAR_SERVO_CENTER        (-90.0f)    /* 直行位 —— 上电 / STOP 目标 */
#define CAR_SERVO_PHYS_OFFSET   135.0f      /* 输出域 → 物理角 安装偏置(°) */
#define CAR_SERVO_LIM_ABS       135.0f      /* 输出域绝对值上限（配置校验用）*/
#define CAR_SERVO_PWM_HZ        50          /* TIM4_CH3 舵机帧频 */

/* ---- 节拍（主循环硬边界，与 doc/代码风格与模块衔接指南.md §4.4 同源）---- */
#define CAR_CTRL_PERIOD_MS      50          /* 速度环/决策节拍 */
#define CAR_DISP_PERIOD_MS      100         /* 显示 + 传感器读节拍（8 页轮转 = 800ms 一轮）*/
#define CAR_IMU_PERIOD_MS       100         /* IMU 更新节拍缺省（IRATE 命令 20~1000 可在线改）*/

/* ---- 巡线初值（功能当前编译期剔除；恢复巡线时用，见 §功能开关）---- */
#define CAR_LF_BASE_SPD         30.0f       /* 巡线基础速度 */
#define CAR_LF_KP               10.0f       /* 巡线 Kp（GK 命令可在线改）*/

/* ---------------------------------------------------------------------------
 *  预留开关位（新增功能开关时在此登记，格式照上：宏 + 启用条件注释）
 * ------------------------------------------------------------------------- */

#endif /* CAR_CONFIG_H */
