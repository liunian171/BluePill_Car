#ifndef CAR_CONFIG_H
#define CAR_CONFIG_H

/**
 * ============================================================================
 *  car_config.h — 整车配置单（组装层知识）
 * ============================================================================
 *
 *  层位：组装层配置（"这台车启用哪些功能 / 标定多少"是车的知识）。
 *  设计决议：doc/开发跟踪.md §设计决议 2026-09-19（功能编译开关，空壳替换方案）。
 *
 *  ▸ 谁可以 include 本文件 ◂
 *    ✅ 组装层 main.c
 *    ✅ CMakeLists.txt（按本文件的宏取舍源文件，单一真值源在这里）
 *    ❌ 组件层 / 桥接层 / 器件层 / 驱动层 —— 禁止 include！
 *       （组件依赖白名单仅 <stdint.h>，义务 7；功能宏进组件 = PC 桩不可编译）
 *       功能开关只允许作用于两处：CMake 源文件列表、组装层接线。
 *
 *  ▸ 开关生效方式（空壳替换为主，组装层接线条件编译为辅）◂
 *    ① 空壳替换（优先，main.c 零修改）：
 *       宏 = 1 → CMake 编 line_follower.c（完整功能）
 *       宏 = 0 → CMake 编 line_follower_stub.c（空实现，12+ 处
 *               line_follower_enable(0) 接管权调用自然变 no-op）
 *    ② 组装层接线条件编译（无对应源文件可替换时用，如链路开关）：
 *       main.c 里 `LINK_*_ENABLED` = 本文件宏 → 禁用链路"接线不存在"
 *       （详见 main.c 的 [P3 双开关] 注释段）
 *
 *  ▸ 改动流程 ◂
 *    ① 改下面的宏值 → ② 必须重新 `cmake --preset Release`（GLOB/取舍在 configure
 *    期完成，只 build 不会生效；**必须 Release**：Debug(-O0) 链接溢出 64KB，
 *    见 AGENTS §三）→ ③ 编译看 Flash/RAM → ④ 回写开发跟踪。
 *
 *  ▸ 标定集中（待办 3②）◂
 *    本文件将来兼收整车标定表（PPR / max_rpm / 轮距等，现散在 main.c 配置
 *    结构体）。标定迁移属独立重构条目，本文件先只承载功能开关，不提前搬值。
 * ============================================================================
 */

/* ---------------------------------------------------------------------------
 *  功能开关（1 = 编译进固件 / 0 = 编译期剔除）
 * ------------------------------------------------------------------------- */

/* 巡线功能（line_follower 状态机 + 5 路灰度决策链）
 * 0 的含义：巡线永不接管运动意图；L/LA/GK/GD/GS/GI/GC/GT 命令变为
 *          no-op 空壳（部分应答仍回显参数，真伪以 OLED 页 7 "LINE:OFF" 为准）
 * 改回 1 的条件：巡线实车整定重启（L-4）或独立小车模式启用时；
 *          当前口径（2026-09-19）：ROS 下位机模式主用，巡线暂不使用 → 0   */
#define CAR_FEATURE_LINE_FOLLOWER 0

/* ---------------------------------------------------------------------------
 *  链路开关（双链路仲裁 P3 开关收口，详 doc/双链路仲裁设计文档.md §5）
 *  语义 = "这条链路的接线不存在"，**不改协议、不改组件**，只改组装层接线。
 * ------------------------------------------------------------------------- */

/* USB CDC 链路（主用：ROS 下位机主链，枚举为 0483:5740 的 COM 口）
 * 0 的含义：usb ringbuf 不消费 / usb_alive 恒假 / 仲裁固定走 UART /
 *          LINK USB 命令被拒（回 LINK:OFF）
 * ⚠️ =0 **不省 Flash** —— USB 中间件由 CubeMX 生成，编译剔除需动生成代码，
 *    12KB 成本已付，不值（设计文档 §5 明确）；本开关是"语义收口"不是"瘦身手段" */
#define CAR_FEATURE_USB        1

/* BT04 蓝牙 SPP 链路（备链：USART2 PA2/PA3，9600-8N1）
 * 0 的含义：不开 UART 中断接收 / UART 发送 no-op / 仲裁固定走 USB /
 *          LINK UART 命令被拒（回 LINK:OFF）
 * 典型用法：纯 USB 场测（不接 BT04，免得 PA3 悬空输入引入噪声） */
#define CAR_FEATURE_UART       1

/* ⚠️ 两宏不得同时为 0（车失联）—— CMakeLists 在 configure 期直接报错拒绝。
 * 四组合（00 被拒 / 01 / 10 / 11）均在编译矩阵中验证，见 doc/开发跟踪.md P3 条。 */

/* ---------------------------------------------------------------------------
 *  预留开关位（新增功能开关时在此登记，格式照上：宏 + 启用条件注释）
 * ------------------------------------------------------------------------- */

#endif /* CAR_CONFIG_H */
