#ifndef ODOM_H
#define ODOM_H

/**
 * ============================================================================
 *  感知组件 — odom（里程计）：编码器 + IMU → 增量位姿 (ΔX, ΔY, Δθ)
 * ============================================================================
 *
 *  层位（自顶向下，详见 doc/代码风格与模块衔接指南 §1.2）：
 *    组装层      main.c          节拍接线（50ms）/ 上行帧组包
 *    感知组件    odom            ← 本文件：裸数(编码器计数/IMU yaw) → 物理量(增量位姿)
 *    驱动层      encoder / imu_bridge   裸数来源（经函数指针注入）
 *
 *  ▸ 需求来源（上位机对接, 2026-09-14 确认）◂
 *    上位机（ROS/Jetson/RDK）需要增量位姿做 odometry 融合：
 *      帧语义 = 帧头 | ΔX | ΔY | Δθ | 时间戳(ms)，不要校验，只要增量
 *      （坐标漂移由上位机纠正，下位机不维护绝对坐标的权威性）
 *    本组件只负责"算"，组帧与发送归组装层（main.c）。
 *
 *  ▸ 本组件职责（三件）◂
 *    1) 增量解算   编码器计数差 → 左右轮位移 → 差速运动学 → Δs/Δθ
 *    2) 航向融合   Δθ 优先取 IMU yaw 差分（打滑不误），io 未注入时回退编码器差分
 *    3) 位姿积分   供 OLED/调试的累计位姿（权威在上位机，此处仅为本地参考）
 *
 *  ▸ 坐标域与单位声明（义务 8）◂
 *    ΔX/ΔY : 车体系增量, 单位 mm, X=车头正前, Y=车体左侧, 中点积分
 *            （ΔX = Δs·cos(Δθ/2), ΔY = Δs·sin(Δθ/2), 上位机可精确重建轨迹）
 *    Δθ    : 航向角增量, 单位 °, 逆时针为正, 归一到 (-180, 180]
 *    yaw   : 与 imu_bridge 同源（°, 逆时针为正）
 *
 *  ▸ 时间基准（义务 5）◂
 *    tick 由调用方传入（now_ms）；内部仅存"上次更新时刻"算 dt，
 *    不读时钟、无超时逻辑。dt 超界（≤0 或 >ODOM_DT_MAX_MS）视为节拍失步：
 *    重同步基准并返回错误（该帧不产出有效值，与 speed_loop_measure 同策略）。
 *
 *  ▸ 错误通道（义务 6）◂
 *    统一返回码；未初始化 / id 越界 / 指针 NULL / dt 超界一律非 OK，绝不静默。
 *
 *  ▸ 依赖白名单 ◂
 *    仅 <stdint.h>（零 HAL、零项目依赖）→ 满足义务 7（PC 桩可编译）
 *    sin/cos 由 PC 桩与固件各自的 math.h 提供（实现文件内 include）。
 * ============================================================================
 */

#include <stdint.h>

/* ---- dt 守卫：超过此值(ms)视为节拍失步，重同步并报错 ---- */
#define ODOM_DT_MAX_MS          2000u

/* ---- 编码器通道数（本车 2；与 speed_loop/SPEED_LOOP_MAX_CH 对齐留裕量）---- */
#define ODOM_MAX_ENC            2

/* ---- 返回码（错误通道；模块内保持一致）---- */
typedef enum {
    ODOM_OK           = 0,   /* 调用成功（含 resync 后首帧的零增量） */
    ODOM_ERR_NOT_INIT = 1,   /* 组件未初始化 */
    ODOM_ERR_BAD_ARG  = 2,   /* 入参非法 / dt 超界（已重同步，该帧丢弃） */
    ODOM_ERR_BAD_CFG  = 3,   /* 初始化配置非法（拒绝初始化） */
} odom_ret_t;

/* ============================================================================
 *  注入通道（组装层绑定；本组件只持函数指针，不认识 encoder/imu_bridge）
 * ============================================================================ */

/* 读编码器原始计数 → 组装层绑定 encoder_get_count */
typedef int32_t (*odom_enc_fn)(uint8_t enc_id);

/* 读 IMU yaw(°, 逆时针为正) → 组装层绑定 imu_bridge_get_yaw；可注入 NULL
 * = NULL 时 Δθ 回退为编码器差分（需 wheel_track_mm > 0） */
typedef void (*odom_yaw_fn)(float *yaw_deg_out);

typedef struct {
    odom_enc_fn read_enc;   /* 必填 */
    odom_yaw_fn get_yaw;    /* 可为 NULL → Δθ 用编码器差分 */
} odom_io_t;

/* ============================================================================
 *  配置（全部为标定/硬件知识，"车知识"）
 * ============================================================================ */
typedef struct {
    float   ppr[ODOM_MAX_ENC];    /* 编码器每转计数（实测 1466），>0 */
    float   wheel_circ_mm;        /* 轮周长 mm（README 权威 20.5cm → 205.0），>0 */
    float   wheel_track_mm;       /* 轮距 mm ⚠️ 待标定 — 仅编码器差分 Δθ 用；
                                     注入 get_yaw 后不参与（置 0 即可） */
    float   enc_span;             /* 计数模值：16 位定时器 = 65536（回绕校正）；0 = 不校正 */
    int8_t  sign[ODOM_MAX_ENC];   /* 计数符号修正：**必须镜像 speed_loop 的 fb_sign**
                                     （E2 硬件接反 → id1 = -1；两侧失配 = 增量方向反） */
    int8_t  yaw_sign;             /* IMU yaw → 车体航向 符号适配（+1 同向 / -1 反向）。
                                     对外约定 Δθ 逆时针为正（数学惯例/ROS 一致）；
                                     本车 MPU6050 安装实测 yaw 顺时针为正 → 配 -1
                                     （2026-09-14 真机实测，见开发跟踪 R-1） */
} odom_cfg_t;

/* ============================================================================
 *  增量输出（一帧 = 一次 odom_update）
 * ============================================================================ */
typedef struct {
    float    dx_mm;       /* 车体系 X 增量（mm, 车头正前） */
    float    dy_mm;       /* 车体系 Y 增量（mm, 左为正） */
    float    dtheta_deg;  /* 航向增量（°, 逆时针为正, (-180,180]） */
    uint32_t dt_ms;       /* 本帧时长（自上次 update） */
} odom_delta_t;

/* ============================================================================
 *  接口
 * ============================================================================ */

/* 初始化：注入标定表与 IO 通道；非法配置（ppr/circ<=0、sign=0、编码器模式
 * 却 track<=0）返回 ERR_BAD_CFG 且不置位。 */
odom_ret_t odom_init(const odom_cfg_t *cfg, const odom_io_t *io);

/* 重同步基准（init 后/上报使能时调用一次：记录当前计数与 yaw 为零点） */
odom_ret_t odom_resync(uint32_t now_ms);

/* 节拍驱动：每 50ms 调用一次。解算自上帧以来的增量并累加位姿。
 * 首帧（resync 后）返回零增量 + ODOM_OK（上游可直接发送，语义 = 无位移）。 */
odom_ret_t odom_update(uint32_t now_ms, odom_delta_t *out);

/* 累计位姿读出（本地参考；权威在上位机）。x/y 单位 mm, theta 单位 °。 */
odom_ret_t odom_get_pose(float *x_mm, float *y_mm, float *theta_deg);

uint8_t odom_is_init(void);

#endif /* ODOM_H */
